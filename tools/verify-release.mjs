import fs from 'node:fs';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
const fail = message => { throw new Error(message); };
const repository = process.env.GITHUB_REPOSITORY || process.argv[2];
const envelope = JSON.parse(fs.readFileSync('release/king-booster-update.json','utf8'));
if(envelope.Format!==1)fail('Formato firma non supportato');
const xml=fs.readFileSync('UpdatePublicKey.xml','utf8');
const part=name=>{const m=xml.match(new RegExp('<'+name+'>([^<]+)</'+name+'>'));if(!m)fail('Chiave pubblica incompleta');return Buffer.from(m[1],'base64').toString('base64url');};
const key=crypto.createPublicKey({key:{kty:'RSA',n:part('Modulus'),e:part('Exponent')},format:'jwk'});
const bytes=Buffer.from(envelope.Payload,'base64');
if(!crypto.verify('RSA-SHA256',bytes,key,Buffer.from(envelope.Signature,'base64')))fail('Firma non valida');
const m=JSON.parse(bytes);
if(m.Product!=='KING_BOOSTER'||m.Platform!=='windows-x64'||m.Channel!=='stable'||m.Repository!==repository||m.MinimumUpdater!==1)fail('Rilascio non coerente con questo repository');
if(!/^\d{1,5}\.\d{1,5}\.\d{1,5}$/.test(m.Version))fail('Versione non valida');
const expected='https://github.com/'+repository+'/releases/download/v'+m.Version+'/KING_BOOSTER_runtime_x64.zip';
if(m.PackageUrl!==expected)fail('URL pacchetto non coerente');
const zip=fs.readFileSync('release/KING_BOOSTER_runtime_x64.zip');
if(zip.length!==m.PackageSize||zip.length>33554432||crypto.createHash('sha256').update(zip).digest('hex')!==m.PackageSha256)fail('Pacchetto diverso da quello firmato');
fs.writeFileSync('release/verified-manifest.json',JSON.stringify(m));
execFileSync(process.platform==='win32'?'python':'python3',['tools/verify_archive.py'],{stdio:'inherit'});
fs.writeFileSync('release/version.txt',m.Version);
fs.writeFileSync('release/notes.md','# KING BOOSTER '+m.Version+'\n\n'+(m.Notes||'')+'\n');
console.log('Rilascio firmato verificato: '+m.Version);
